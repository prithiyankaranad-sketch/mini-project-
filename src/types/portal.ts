import { z } from "zod";
export const categorySchema = z.object({
  id: z.string(),
  name: z.string(),
  active: z.boolean(),
});
export const eventSchema = z.object({
  id: z.string(),
  title: z.string(),
  short_description: z.string(),
  description: z.string(),
  department: z.string(),
  venue: z.string(),
  contact: z.string(),
  category_id: z.string().nullable(),
  starts_at: z.string(),
  ends_at: z.string(),
  registration_opens_at: z.string(),
  registration_closes_at: z.string(),
  cancellation_closes_at: z.string(),
  capacity: z.number(),
  mode: z.enum(["individual", "team"]),
  min_team_size: z.number(),
  max_team_size: z.number(),
  fee: z.number(),
  waitlist_enabled: z.boolean(),
  eligible_departments: z.array(z.string()),
  eligible_years: z.array(z.number()),
  require_roster: z.boolean(),
  certificate_enabled: z.boolean(),
  certificate_attendance_percent: z.number(),
  attendance_mode: z.enum(["event", "session"]),
  attendance_finalized: z.boolean(),
  feedback_requires_attendance: z.boolean(),
  status: z.string(),
  effective_status: z.string(),
  registered_count: z.number(),
  poster_path: z.string().nullable(),
});
export type EventRecord = z.infer<typeof eventSchema>;
export const registrationSchema = z.object({
  id: z.string(),
  event_id: z.string(),
  user_id: z.string(),
  team_id: z.string().nullable(),
  reference: z.string(),
  status: z.string(),
  event_title: z.string(),
  starts_at: z.string(),
  ends_at: z.string(),
  venue: z.string(),
  event_status: z.string(),
  attendance_percent: z.number(),
  certificate_enabled: z.boolean(),
  feedback_requires_attendance: z.boolean(),
  cancellation_closes_at: z.string(),
  created_at: z.string(),
});
export const participantSchema = z.object({
  id: z.string(),
  reference: z.string(),
  status: z.string(),
  created_at: z.string(),
  team_id: z.string().nullable(),
  user_id: z.string(),
  full_name: z.string(),
  rrn: z.string(),
  department: z.string(),
  study_year: z.number(),
  email: z.string(),
  attendance_percent: z.number(),
});
export const sessionSchema = z.object({
  id: z.string(),
  event_id: z.string(),
  title: z.string(),
  description: z.string(),
  starts_at: z.string(),
  ends_at: z.string(),
  venue: z.string(),
  speaker: z.string(),
  display_order: z.number(),
});
export const teamSchema = z.object({
  id: z.string(),
  event_id: z.string(),
  name: z.string(),
  leader_id: z.string(),
  status: z.string(),
  members: z.array(
    z.object({ user_id: z.string(), name: z.string(), status: z.string() }),
  ),
});
export const notificationSchema = z.object({
  id: z.string(),
  event_id: z.string().nullable(),
  title: z.string(),
  message: z.string(),
  read_at: z.string().nullable(),
  created_at: z.string(),
});
export const attendanceSchema = z.object({
  id: z.string(),
  registration_id: z.string(),
  event_id: z.string(),
  session_id: z.string().nullable(),
  checked_in_at: z.string(),
  present: z.boolean(),
  full_name: z.string(),
  reference: z.string(),
  session_title: z.string().nullable(),
  event_title: z.string(),
});
export const certificateSchema = z.object({
  id: z.string(),
  registration_id: z.string(),
  user_id: z.string(),
  event_id: z.string(),
  type: z.string(),
  status: z.string(),
  verification_id: z.string(),
  object_path: z.string().nullable(),
  snapshot: z.record(z.string(), z.string()),
  issued_at: z.string().nullable(),
  revocation_reason: z.string().nullable(),
});
export const templateSchema = z.object({
  id: z.string(),
  name: z.string(),
  institution: z.string(),
  signatory_name: z.string(),
  signatory_title: z.string(),
  body: z.string(),
});
export const feedbackSchema = z.object({
  id: z.string(),
  event_id: z.string(),
  overall: z.number(),
  organization: z.number(),
  content: z.number(),
  venue: z.number(),
  comments: z.string(),
  suggestions: z.string(),
  created_at: z.string(),
});
export const userSchema = z.object({
  id: z.string(),
  full_name: z.string(),
  email: z.string(),
  rrn: z.string(),
  department: z.string(),
  study_year: z.number(),
  is_active: z.boolean(),
  email_verified: z.boolean(),
  roles: z.array(z.string()).nullable(),
});
export const anyRows = z.array(z.record(z.string(), z.unknown()));
export const statsSchema = z.object({
  events: z.number(),
  registrations: z.number(),
  certificates: z.number(),
  attendance: z.number(),
  users: z.number().nullable(),
  active_students: z.number().nullable(),
  available_seats: z.number().nullable(),
  published_events: z.number(),
  upcoming_registrations: z.number(),
  pending_certificates: z.number().nullable(),
});
export const reportsSchema = z.object({
  sessions: z.array(
    z.object({
      id: z.string(),
      title: z.string(),
      event_title: z.string(),
      registrations: z.number(),
      present: z.number(),
    }),
  ),
  events: z.array(
    z.object({
      id: z.string(),
      title: z.string(),
      status: z.string(),
      capacity: z.number(),
      registrations: z.number(),
      present: z.number(),
      certificates: z.number(),
      rating: z.number().nullable(),
    }),
  ),
  departments: z.array(
    z.object({ department: z.string(), registrations: z.number() }),
  ),
  trends: z.array(z.object({ day: z.string(), registrations: z.number() })),
  categories: z.array(z.object({ name: z.string(), events: z.number() })),
  feedback: z.array(z.object({ rating: z.number(), responses: z.number() })),
});
